        #main equation
        #V0_m = self.V0 * 0.5144 #convert kts to m/s
        rho_air = rho_0 * np.exp(-((0.29/3048) * self.H_m)) #kg/m^3
        A_wind = math.pi * (self.D**2/4) #swept area of blades, m^2 （D/2）**2
        V_wind = (self.H_m/H_0) ** self.alpha * self.V0 #wind speed at hub height, m/s
        #V_u = V_wind
