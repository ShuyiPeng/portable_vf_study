import numpy as np
import math

class WindEnergyModel:
    def __init__(self, alpha, C_p, V_ci, V_co, V_rated, P_rated, D, H_m, V0):
        self.alpha = alpha
        self.C_p = C_p
        self.V_ci = V_ci
        self.V_co = V_co
        self.V_rated = V_rated
        self.P_rated = P_rated
        self.D = D
        self.H_m = H_m
        self.V0 = V0

    def wind_power(self):
        """
        This function calculates the wind power generated by the wind turbine.
        """
        #assumptions:
        #onshore
        #Horizontal Axis Wind Turbine (HAWT)
        #locate on Bleiswijk
        #upstream wind speed equal to wind speed
        #1kts = 0.5144m/s
        #variable speed wind turbine
        #current use 
        #hourly data for wind speed in KNMI

        #parameters (static)
        rho_0 = 1.225 # kg/m^3, density of air at atmospheric pressure
        #Angular_s = 200 #rad/s, angular speed of the wind turbine # chanege with wind speed or not
        H_0 = 10 #m, standard for weather forcast

        #alpha = 0.2 #power-law exponent, ref:https://www.mdpi.com/1996-1073/12/10/1907
        #C_p = 0.5 #maximum power coefficeint, concept ref: https://www.sciencedirect.com/science/article/pii/S1364032113000439#bib12; loss value ref
