        #P_rated = 2e6 #W, rated power, same ref above
        #D = 82#m, rotor diameter, same ref above
        
        #parameters (dynamic)
        #H_m = 80 #m, hub height of onshore wind turbines, ref:https://www.mdpi.com/1996-1073/15/1/302
